    async def submit_application(self, application_id: int) -> UserApplication:
        """提交电子版申请"""
        result = await self.db.execute(
            select(UserApplication).where(UserApplication.application_id == application_id)
        )
        app = result.scalar_one_or_none()
        if not app:
            raise ValueError("申请不存在")
        if app.status != "preparing":
            raise ValueError(f"当前状态为'{app.status}'，不可提交")

        # 检查是否所有材料都已上传
        materials = await self.db.execute(
            select(ApplicationMaterial).where(
                ApplicationMaterial.application_id == application_id,
                ApplicationMaterial.upload_status != "uploaded",
            )
        )
        missing = materials.scalars().all()
        if missing:
            names = [m.material_name for m in missing]
            raise ValueError(f"以下材料尚未上传：{'、'.join(names)}")

        app.status = "submitted"
        app.submitted_at = datetime.now(timezone.utc)
        await self.db.commit()
        await self.db.refresh(app)
        return app

    async def abandon_application(self, application_id: int) -> UserApplication:
        """放弃申请"""
        result = await self.db.execute(
            select(UserApplication).where(UserApplication.application_id == application_id)
        )
        app = result.scalar_one_or_none()
        if not app:
            raise ValueError("申请不存在")
        if app.status not in ("preparing", "submitted", "needs_revision"):
            raise ValueError(f"当前状态为'{app.status}'，不可放弃")
        app.status = "abandoned"
        await self.db.commit()
        await self.db.refresh(app)
        return app

    async def get_user_applications(self, user_id: int) -> list[dict]:
        """获取用户的所有申请"""
        result = await self.db.execute(
            select(UserApplication)
            .where(UserApplication.user_id == user_id)
            .order_by(UserApplication.created_at.desc())
        )
        apps = result.scalars().all()

        items = []
        for app in apps:
            policy = await self.db.get(Policy, app.policy_id)
            # 获取材料状态
            mats = await self.db.execute(
                select(ApplicationMaterial).where(
                    ApplicationMaterial.application_id == app.application_id
                )
            )
            materials = mats.scalars().all()
            total = len(materials)
            uploaded = sum(1 for m in materials if m.upload_status == "uploaded")

            items.append({
                "application_id": app.application_id,
                "policy_id": app.policy_id,
                "policy_title": policy.title if policy else "",
                "status": app.status,
                "applied_at": app.applied_at.isoformat() if app.applied_at else None,
                "submitted_at": app.submitted_at.isoformat() if app.submitted_at else None,
                "materials_total": total,
                "materials_uploaded": uploaded,
                "created_at": app.created_at.isoformat() if app.created_at else None,
                "feedback": app.feedback,
            })
        return items

