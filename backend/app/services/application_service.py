class ApplicationService:
    """申请进度跟踪服务"""

    def __init__(self, db: AsyncSession):
        self.db = db

    async def start_application(self, user_id: int, policy_id: int) -> UserApplication:
        """学生开始准备申请"""
        # 检查是否已申请过
        result = await self.db.execute(
            select(UserApplication).where(
                UserApplication.user_id == user_id,
                UserApplication.policy_id == policy_id,
                UserApplication.status.in_(["preparing", "submitted", "pending_review", "needs_revision", "初审通过", "pending_final", "pending_admin"]),
            )
        )
        existing = result.scalar_one_or_none()
        if existing:
            raise ValueError("您已申请过该政策，请勿重复申请")

        # 检查政策是否存在且已发布
        policy = await self.db.get(Policy, policy_id)
        if not policy or policy.status != "published":
            raise ValueError("政策不存在或未发布")

        # 创建申请
        app = UserApplication(
            user_id=user_id,
            policy_id=policy_id,
            status="preparing",
            applied_at=datetime.now(timezone.utc),
        )
        self.db.add(app)
        await self.db.flush()
        await self.db.refresh(app)

        # 根据政策元数据创建材料清单条目
        meta_result = await self.db.execute(
            select(PolicyMetadata).where(PolicyMetadata.policy_id == policy_id)
        )
        metadata = meta_result.scalar_one_or_none()
        if metadata and metadata.material_list:
            for name in metadata.material_list:
                material = ApplicationMaterial(
                    application_id=app.application_id,
                    material_name=name,
                    upload_status="not_uploaded",
                )
                self.db.add(material)

        await self.db.commit()
        return app

    async def upload_material(self, application_id: int, material_name: str,
                               file_content: bytes, filename: str) -> ApplicationMaterial:
        """上传某项材料"""
        # 查找对应的材料条目
        result = await self.db.execute(
            select(ApplicationMaterial).where(
                ApplicationMaterial.application_id == application_id,
                ApplicationMaterial.material_name == material_name,
            )
        )
        material = result.scalar_one_or_none()
        if not material:
            raise ValueError(f"材料 '{material_name}' 不存在")

        # 保存文件
        app_dir = os.path.join(UPLOAD_DIR, str(application_id))
        os.makedirs(app_dir, exist_ok=True)
        file_path = os.path.join(app_dir, f"{material_name}_{filename}")
        # 避免文件名冲突
        if os.path.exists(file_path):
            base, ext = os.path.splitext(filename)
            file_path = os.path.join(app_dir, f"{material_name}_{base}_{int(time.time())}{ext}")

        with open(file_path, "wb") as f:
            f.write(file_content)

        material.file_name = filename
        material.file_path = file_path
        material.file_size = len(file_content)
        material.upload_status = "uploaded"
        material.uploaded_at = datetime.now(timezone.utc)
        await self.db.commit()
        return material

    async def delete_material(self, application_id: int, material_name: str) -> None:
        """删除已上传的材料"""
        result = await self.db.execute(
            select(ApplicationMaterial).where(
                ApplicationMaterial.application_id == application_id,
                ApplicationMaterial.material_name == material_name,
            )
        )
        material = result.scalar_one_or_none()
        if not material:
            raise ValueError("材料不存在")

        # 删除文件
        if material.file_path and os.path.exists(material.file_path):
            os.remove(material.file_path)

        material.file_name = None
        material.file_path = None
        material.file_size = None
        material.upload_status = "not_uploaded"
